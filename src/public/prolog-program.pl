% posibilidades

puede_aprobar(Codigo) :-
    asignatura(Codigo, _, _, _, _),
    not(aprobada(Codigo)),
    cumple_todos_los_requisitos(Codigo).

puede_cursar(Codigo) :-
    asignatura(Codigo, _, _, _, _),
    not(cursada(Codigo)),
    not(cursando(Codigo)),
    cumple_todos_los_requisitos(Codigo).

puede_cursar_en_periodo(Codigo, A, C) :-
    asignatura(Codigo, _, _, A, C),
    not(cursada(Codigo)),
    not(cursando(Codigo)),
    cumple_todos_los_requisitos(Codigo).

puede_aprobar_en_periodo(Codigo, A, C) :-
